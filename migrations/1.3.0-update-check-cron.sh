#!/usr/bin/env bash
# 1.3.0: ежедневная проверка обновлений (задача jarvis-update-check) у уже установленных помощников.
# Повторный запуск безопасен: update-check-cron.sh install ничего не делает, если задача есть.
# Если помощник в эту минуту не отвечает, обновление не откатываем: задачу позже заведёт doctor-подсказка.
"$JARVIS_HOME_DIR/bin/update-check-cron.sh" install || echo "задача проверки обновлений не заведена, её можно включить позже" >&2
exit 0
